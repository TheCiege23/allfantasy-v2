/**
 * Maps `PlatformBehavioralIntelligence` to the aggregate-only `PlatformIntelligenceBasicV1`.
 *
 * The basic tier is intentionally minimal — safe for browser embedding and
 * public dashboards because it contains no per-league or per-manager identifiers
 * and no absolute counts that reveal platform scale.
 *
 * Included: engagement score/tier, league health percentages (only), momentum
 *   signal, trend confidence, completeness, derivedAt.
 * Everything else is excluded.
 *
 * @param intel   Internal platform intelligence object (not mutated)
 * @param requestId  UUID generated by the route handler for tracing
 */
export function resolvePlatformIntelligenceBasic(
  intel: PlatformBehavioralIntelligence,
  requestId: string,
): IntelligenceApiResponse<PlatformIntelligenceBasicV1> {
  // STRIPS: leagueHealthDistribution absolute counts, commissionerQualityDistribution,
  //         retentionDistribution, tradeEcosystem, waiverEcosystem, draftParticipation
  //         (all rates), engagementTrends counts/ratios, activityHeatmap,
  //         interventionOpportunities, uncertainty, warnings, provenance
  const data: PlatformIntelligenceBasicV1 = {
    platformEngagementScore: intel.platformEngagementScore,
    platformEngagementTier:  intel.platformEngagementTier,
    leagueHealthSummary: {
      healthyPercent: intel.leagueHealthDistribution.healthyPercent,
      atRiskPercent:  intel.leagueHealthDistribution.atRiskPercent,
    },
    momentumSignal:  intel.engagementTrends.momentumSignal,
    trendConfidence: intel.engagementTrends.trendConfidence,
    completeness:    intel.completeness,
    derivedAt:       intel.derivedAt,
  }
  return { data, meta: buildMeta(intel.derivedAt, intel.completeness, 'basic', requestId) }
}

// ─────────────────────────────────────────────────────────────────────────────
// Platform Intelligence — Full tier resolver
// ─────────────────────────────────────────────────────────────────────────────

function mapPlatformEcosystemDimension(
  dim: PlatformEcosystemDimension,
): PlatformEcosystemDimensionV1 {
  // STRIPS: totalEvents, activeLeagues, totalLeagues, warnings
  return {
    tier:                dim.tier,
    activeLeaguePercent: dim.activeLeaguePercent,
    perLeagueRate:       dim.perLeagueRate,
    perManagerRate:      dim.perManagerRate,
  }
}

function mapHeatmapCell(cell: HeatmapCell): PlatformHeatmapCellV1 {
  return { dayOfWeek: cell.dayOfWeek, hour: cell.hour, count: cell.count }
}

function mapIntervention(opp: PlatformInterventionOpportunity): PlatformInterventionV1 {
  // signal IS included in external API — machine-readable for operator-side routing
  // managerId IS included — it is the caller's own tenant-scoped identifier
  const result: PlatformInterventionV1 = {
    opportunityId: opp.opportunityId,
    scope:         opp.scope,
    priority:      opp.priority,
    leagueId:      opp.leagueId,
    signal:        opp.signal,
    message:       opp.message,
  }
  if (opp.managerId !== undefined) result.managerId = opp.managerId
  return result
}

/**
 * Maps `PlatformBehavioralIntelligence` to the full `PlatformIntelligenceV1` contract.
 *
 * Includes all platform-scope signals. Enforces stripping of internal fields:
 *   - Ecosystem dimensions lose `totalEvents`, `activeLeagues`, `totalLeagues`, `warnings`
 *   - `engagementTrends.warnings` excluded
 *   - `activityHeatmap.warnings` excluded
 *   - Top-level `warnings` excluded
 *   - `provenance` (internal data-pipeline metadata) excluded
 *
 * @param intel   Internal platform intelligence object (not mutated)
 * @param requestId  UUID generated by the route handler for tracing
 */
export function resolvePlatformIntelligenceFull(
  intel: PlatformBehavioralIntelligence,
  requestId: string,
): IntelligenceApiResponse<PlatformIntelligenceV1> {
  // STRIPS: top-level warnings, provenance
  const data: PlatformIntelligenceV1 = {
    platformEngagementScore: intel.platformEngagementScore,
    platformEngagementTier:  intel.platformEngagementTier,
    uncertainty:             intel.uncertainty,

    leagueHealthDistribution: {
      elite:          intel.leagueHealthDistribution.elite,
      active:         intel.leagueHealthDistribution.active,
      moderate:       intel.leagueHealthDistribution.moderate,
      passive:        intel.leagueHealthDistribution.passive,
      dormant:        intel.leagueHealthDistribution.dormant,
      totalLeagues:   intel.leagueHealthDistribution.totalLeagues,
      healthyPercent: intel.leagueHealthDistribution.healthyPercent,
      atRiskPercent:  intel.leagueHealthDistribution.atRiskPercent,
    },

    commissionerQualityDistribution: {
      light:             intel.commissionerQualityDistribution.light,
      moderate:          intel.commissionerQualityDistribution.moderate,
      heavy:             intel.commissionerQualityDistribution.heavy,
      critical:          intel.commissionerQualityDistribution.critical,
      totalLeagues:      intel.commissionerQualityDistribution.totalLeagues,
      managedPercent:    intel.commissionerQualityDistribution.managedPercent,
      overloadedPercent: intel.commissionerQualityDistribution.overloadedPercent,
    },

    retentionDistribution: {
      managersByCriticalRisk:     intel.retentionDistribution.managersByCriticalRisk,
      managersByHighRisk:         intel.retentionDistribution.managersByHighRisk,
      managersByMediumRisk:       intel.retentionDistribution.managersByMediumRisk,
      managersByLowRisk:          intel.retentionDistribution.managersByLowRisk,
      totalManagers:              intel.retentionDistribution.totalManagers,
      managerCriticalRiskPercent: intel.retentionDistribution.managerCriticalRiskPercent,
      managerAtRiskPercent:       intel.retentionDistribution.managerAtRiskPercent,
      leaguesByCriticalRisk:      intel.retentionDistribution.leaguesByCriticalRisk,
      leaguesByHighRisk:          intel.retentionDistribution.leaguesByHighRisk,
      leaguesByMediumRisk:        intel.retentionDistribution.leaguesByMediumRisk,
      leaguesByLowRisk:           intel.retentionDistribution.leaguesByLowRisk,
      totalLeagues:               intel.retentionDistribution.totalLeagues,
      leagueCriticalRiskPercent:  intel.retentionDistribution.leagueCriticalRiskPercent,
      leagueAtRiskPercent:        intel.retentionDistribution.leagueAtRiskPercent,
    },

    // STRIPS per ecosystem: totalEvents, activeLeagues, totalLeagues, warnings
    tradeEcosystem:    mapPlatformEcosystemDimension(intel.tradeEcosystem),
    waiverEcosystem:   mapPlatformEcosystemDimension(intel.waiverEcosystem),
    draftParticipation: mapPlatformEcosystemDimension(intel.draftParticipation),

    engagementTrends: {
      // STRIPS: warnings
      sevenDayEventCount:           intel.engagementTrends.sevenDayEventCount,
      thirtyDayEventCount:          intel.engagementTrends.thirtyDayEventCount,
      recentActivityRatio:          intel.engagementTrends.recentActivityRatio,
      recentlyActiveManagerPercent: intel.engagementTrends.recentlyActiveManagerPercent,
      momentumSignal:               intel.engagementTrends.momentumSignal,
      trendConfidence:              intel.engagementTrends.trendConfidence,
    },

    activityHeatmap: {
      // STRIPS: warnings
      cells:               intel.activityHeatmap.cells.map(mapHeatmapCell),
      peakCellKey:         intel.activityHeatmap.peakCellKey,
      peakDayOfWeek:       intel.activityHeatmap.peakDayOfWeek,
      peakHour:            intel.activityHeatmap.peakHour,
      peakCount:           intel.activityHeatmap.peakCount,
      totalEventsAnalyzed: intel.activityHeatmap.totalEventsAnalyzed,
    },

    interventionOpportunities: intel.interventionOpportunities.map(mapIntervention),

    completeness: intel.completeness,
    derivedAt:    intel.derivedAt,
  }
  return { data, meta: buildMeta(intel.derivedAt, intel.completeness, 'platform', requestId) }
}
