/**
 * Decision OS — Phase 5.6 Intelligence API Internal Resolvers.
 *
 * Pure bridge functions that map internal behavioral intelligence types to the
 * curated external API contracts defined in `api/contracts.ts`.
 *
 * These resolvers are the single authoritative enforcement point for all
 * privacy stripping rules. Every excluded field is annotated with a STRIPS comment.
 *
 * Architecture constraints (ADR_F5_6_INTELLIGENCE_API_RESOLVERS.md):
 *   - Pure functions: no IO, no DB access, no auth, no network calls
 *   - No input mutation
 *   - No internal Decision OS fields in output (warnings, derivedFrom, provenance, etc.)
 *   - managerId / leagueId echoed as-is (caller's own tenant-scoped IDs)
 *
 * Usage (future Phase 5.7 route handler):
 *   const data = resolveManagerIntelligence(intel, requestId, 'manager')
 *   return NextResponse.json(data)
 */

import type { ManagerBehavioralIntelligence, ManagerNudge } from '../manager-intelligence'
import type {
  LeagueBehavioralIntelligence,
  LeagueActivityDimension,
  LeagueCommissionerRecommendation,
} from '../league-intelligence'
import type {
  PlatformBehavioralIntelligence,
  PlatformEcosystemDimension,
  HeatmapCell,
  PlatformInterventionOpportunity,
} from '../platform-intelligence'
import type {
  IntelligenceApiResponse,
  IntelligenceApiMeta,
  IntelligenceTier,
  ManagerIntelligenceV1,
  ManagerEngagementDimensionsV1,
  ManagerNudgeV1,
  LeagueIntelligenceV1,
  LeagueActivityDimensionV1,
  LeagueRecommendationV1,
  PlatformIntelligenceBasicV1,
  PlatformIntelligenceV1,
  PlatformEcosystemDimensionV1,
  PlatformHeatmapCellV1,
  PlatformInterventionV1,
} from './contracts'

// ── Envelope builder ──────────────────────────────────────────────────────────

function buildMeta(
  derivedAt: string,
  completeness: number,
  tier: IntelligenceTier,
  requestId: string,
): IntelligenceApiMeta {
  return { requestId, derivedAt, completeness, version: 'v1', tier }
}

// ─────────────────────────────────────────────────────────────────────────────
// Manager Intelligence resolver
// ─────────────────────────────────────────────────────────────────────────────

function mapManagerNudge(nudge: ManagerNudge): ManagerNudgeV1 {
  // STRIPS: signal (internal machine-readable trigger key)
  // STRIPS: supportingEventIds (internal event reference list)
  return {
    nudgeId:  nudge.nudgeId,
    priority: nudge.priority,
    category: nudge.category,
    message:  nudge.message,
  }
}

function mapEngagementDimensions(
  intel: ManagerBehavioralIntelligence,
): ManagerEngagementDimensionsV1 {
  // STRIPS (per dimension): eventCount, lastEventAt, warnings
  return {
    lineup: { score: intel.lineupEngagement.score, level: intel.lineupEngagement.level },
    waiver: { score: intel.waiverEngagement.score, level: intel.waiverEngagement.level },
    trade:  { score: intel.tradeEngagement.score,  level: intel.tradeEngagement.level  },
    draft:  { score: intel.draftEngagement.score,  level: intel.draftEngagement.level  },
  }
}

/**
 * Maps `ManagerBehavioralIntelligence` to the external `ManagerIntelligenceV1` contract.
 *
 * Enforces all privacy stripping rules for the manager intelligence endpoint:
 *   - Nudges lose `signal` and `supportingEventIds`
 *   - Engagement dimensions lose `eventCount`, `lastEventAt`, `warnings`
 *   - `inactivityWarning`, `derivedFrom`, `lookbackDays`, `warnings` are excluded
 *
 * @param intel   Internal manager intelligence object (not mutated)
 * @param requestId  UUID generated by the route handler for tracing
 * @param tier    Caller's effective tier (usually 'manager'; recorded in meta)
 */
export function resolveManagerIntelligence(
  intel: ManagerBehavioralIntelligence,
  requestId: string,
  tier: IntelligenceTier,
): IntelligenceApiResponse<ManagerIntelligenceV1> {
  // STRIPS: inactivityWarning, derivedFrom, lookbackDays, warnings
  const data: ManagerIntelligenceV1 = {
    managerId:              intel.managerId,
    leagueId:               intel.leagueId,
    participationTier:      intel.participationTier,
    retentionRisk:          intel.retentionRisk,
    retentionRiskReasons:   [...intel.retentionRiskReasons],
    overallEngagementScore: intel.overallEngagementScore,
    engagementDimensions:   mapEngagementDimensions(intel),
    daysSinceLastActivity:  intel.daysSinceLastActivity,
    isInactive:             intel.isInactive,
    nudges:                 intel.nudges.map(mapManagerNudge),
    completeness:           intel.completeness,
    derivedAt:              intel.derivedAt,
  }
  return { data, meta: buildMeta(intel.derivedAt, intel.completeness, tier, requestId) }
}

// ─────────────────────────────────────────────────────────────────────────────
// League Intelligence resolver
// ─────────────────────────────────────────────────────────────────────────────

function mapActivityDimension(dim: LeagueActivityDimension): LeagueActivityDimensionV1 {
  // STRIPS: count (raw event total), warnings
  return {
    tier:           dim.tier,
    perManagerRate: dim.perManagerRate,
  }
}

function mapLeagueRecommendation(
  rec: LeagueCommissionerRecommendation,
): LeagueRecommendationV1 {
  // STRIPS: signal (internal machine-readable trigger key)
  return {
    recommendationId: rec.recommendationId,
    priority:         rec.priority,
    category:         rec.category,
    message:          rec.message,
  }
}

/**
 * Maps `LeagueBehavioralIntelligence` to the external `LeagueIntelligenceV1` contract.
 *
 * Enforces all privacy stripping rules for the league intelligence endpoint:
 *   - Activity dimensions lose `count` and `warnings`
 *   - Recommendations lose `signal`
 *   - `retentionRiskReasons`, `commissionerWorkloadItems`, `healthNarrativeInputs`,
 *     `inactiveManagerCount`, `derivedFrom`, `managerCount`, `lookbackDays`,
 *     `warnings` are excluded
 *
 * @param intel   Internal league intelligence object (not mutated)
 * @param requestId  UUID generated by the route handler for tracing
 * @param tier    Caller's effective tier (usually 'commissioner'; recorded in meta)
 */
export function resolveLeagueIntelligence(
  intel: LeagueBehavioralIntelligence,
  requestId: string,
  tier: IntelligenceTier,
): IntelligenceApiResponse<LeagueIntelligenceV1> {
  // STRIPS: retentionRiskReasons, commissionerWorkloadItems, healthNarrativeInputs,
  //         inactiveManagerCount, derivedFrom, managerCount, lookbackDays, warnings
  const data: LeagueIntelligenceV1 = {
    leagueId:               intel.leagueId,
    leagueEngagementScore:  intel.leagueEngagementScore,
    leagueEngagementTier:   intel.leagueEngagementTier,
    participationDistribution: { ...intel.participationDistribution },
    tradeActivity:          mapActivityDimension(intel.tradeActivity),
    waiverActivity:         mapActivityDimension(intel.waiverActivity),
    draftActivity:          mapActivityDimension(intel.draftActivity),
    retentionRisk:          intel.retentionRisk,
    commissionerWorkload:   intel.commissionerWorkload,
    recommendations:        intel.recommendations.map(mapLeagueRecommendation),
    completeness:           intel.completeness,
    derivedAt:              intel.derivedAt,
  }
  return { data, meta: buildMeta(intel.derivedAt, intel.completeness, tier, requestId) }
}

